-- ============================================================
-- ЗАДАНИЕ: AOV и LTV для пользователей Spotify
-- СУБД: MySQL
-- База данных: spotify_db
-- Таблицы: users, payments
-- ============================================================

USE spotify_db;


-- ============================================================
-- 1. AOV (Average Order Value) для каждого пользователя
-- Средняя сумма одной оплаты пользователя.
--
-- Формула:
-- AOV = сумма всех оплат пользователя / количество оплат
--
-- Пользователи без оплат также выводятся с AOV = 0.
-- ============================================================

SELECT
    u.user_id,
    ROUND(COALESCE(SUM(p.amount), 0), 2) AS total_paid,
    COUNT(p.payment_id) AS payments_count,
    ROUND(
        COALESCE(SUM(p.amount) / NULLIF(COUNT(p.payment_id), 0), 0),
        2
    ) AS AOV
FROM users u
LEFT JOIN payments p
    ON u.user_id = p.user_id
GROUP BY u.user_id
ORDER BY AOV DESC, u.user_id;


-- ============================================================
-- 2. LTV (Lifetime Value) для каждого пользователя
-- Общая сумма денег, которую пользователь принёс сервису
-- за весь период, представленный в базе.
--
-- Формула:
-- LTV = SUM(amount) по всем оплатам пользователя
--
-- Пользователи без оплат имеют LTV = 0.
-- ============================================================

SELECT
    u.user_id,
    ROUND(COALESCE(SUM(p.amount), 0), 2) AS LTV
FROM users u
LEFT JOIN payments p
    ON u.user_id = p.user_id
GROUP BY u.user_id
ORDER BY LTV DESC, u.user_id;


-- ============================================================
-- 3. ТОП-5 пользователей с самым высоким LTV
-- ============================================================

SELECT
    u.user_id,
    ROUND(COALESCE(SUM(p.amount), 0), 2) AS LTV
FROM users u
LEFT JOIN payments p
    ON u.user_id = p.user_id
GROUP BY u.user_id
ORDER BY LTV DESC, u.user_id
LIMIT 5;


-- ============================================================
-- 4. Средний LTV по всем клиентам
--
-- Важно: средний LTV считается по ВСЕМ пользователям,
-- включая пользователей без оплат.
--
-- Формула:
-- Average LTV = общий доход / количество всех пользователей
--
-- Для данной БД:
-- общий доход = 43 000
-- количество пользователей = 20
-- средний LTV = 2 150
-- ============================================================

SELECT
    COUNT(DISTINCT u.user_id) AS total_users,
    ROUND(COALESCE(SUM(p.amount), 0), 2) AS total_revenue,
    ROUND(
        COALESCE(SUM(p.amount), 0) / COUNT(DISTINCT u.user_id),
        2
    ) AS average_LTV
FROM users u
LEFT JOIN payments p
    ON u.user_id = p.user_id;


-- ============================================================
-- 5. Проверка: средний LTV и стоимость привлечения клиента
--
-- Стоимость привлечения одного нового клиента (CAC) = 3 000 тг.
--
-- Если Average LTV >= CAC, привлечение окупается по текущему
-- среднему LTV.
-- Если Average LTV < CAC, средняя выручка за весь жизненный цикл
-- клиента ниже стоимости привлечения.
-- ============================================================

SELECT
    3000 AS CAC,
    ROUND(
        COALESCE(SUM(p.amount), 0) / COUNT(DISTINCT u.user_id),
        2
    ) AS average_LTV,
    ROUND(
        (
            COALESCE(SUM(p.amount), 0) / COUNT(DISTINCT u.user_id)
        ) - 3000,
        2
    ) AS LTV_minus_CAC,
    CASE
        WHEN (
            COALESCE(SUM(p.amount), 0) / COUNT(DISTINCT u.user_id)
        ) >= 3000
        THEN 'Средний LTV покрывает стоимость привлечения'
        ELSE 'Средний LTV не покрывает стоимость привлечения'
    END AS conclusion
FROM users u
LEFT JOIN payments p
    ON u.user_id = p.user_id;


