--
-- Средний LTV = 2 150 тг.
-- Стоимость привлечения одного клиента = 3 000 тг.
--
-- 2 150 < 3 000, поэтому при текущем среднем LTV затраты
-- на привлечение нового клиента не окупаются.
--
-- Разница:
-- 2 150 - 3 000 = -850 тг.
--
